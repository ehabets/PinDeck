import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import net from 'node:net';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('..',import.meta.url));
const delay=ms=>new Promise(r=>setTimeout(r,ms));
async function until(fn){for(let i=0;i<150;i++){let r;try { r=await fn(); } catch(e) { if (!(e instanceof SyntaxError)) throw e; } if(r)return r;await delay(30);}throw new Error('Timed out');}
test('HTTP model switching keeps the old session on failure and transfers context only with consent',async t=>{
 const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'pindeck-integration-'));const home=path.join(tmp,'state'),deck=path.join(tmp,'deck');fs.mkdirSync(deck);
 fs.writeFileSync(path.join(deck,'index.html'),'<html><body><div class="reveal"><div class="slides"><section><h1>Test</h1></section></div></div></body></html>');
 fs.writeFileSync(path.join(deck,'theme.css'),'h1 { color: blue; }');
 const fake=path.join(root,'test/fixtures/fake-agent'),logFile=path.join(tmp,'log');
 const listener=net.createServer();await new Promise((resolve,reject)=>listener.once('error',reject).listen(0,'127.0.0.1',resolve));const port=listener.address().port;await new Promise(r=>listener.close(r));
 let errors='';const child=spawn(process.execPath,[path.join(root,'server.mjs'),deck,'--port',String(port)],{env:{...process.env,PINDECK_HOME:home,CLAUDE_BIN:fake,CODEX_BIN:fake,FAKE_AGENT_LOG:logFile},stdio:['ignore','pipe','pipe']});
 child.stderr.on('data',d=>errors+=d);
 t.after(async()=>{child.kill('SIGTERM');await new Promise(r=>child.exitCode!==null?r():child.once('exit',r));fs.rmSync(tmp,{recursive:true,force:true});});
 const serverFile=path.join(home,'servers',`${child.pid}.json`);
 await until(()=>fs.existsSync(serverFile));
 const {token}=JSON.parse(fs.readFileSync(serverFile));
 const api=async(url,body)=>{const r=await fetch(`http://127.0.0.1:${port}/api/${url}`,{method:body===undefined?'GET':'POST',headers:{'x-editor-token':token,'content-type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});return {status:r.status,data:await r.json()};};
 await until(async()=>{if(child.exitCode!==null)throw new Error(errors);try{return (await api('ping')).status===200;}catch{return false;}});
 const models=await api('models');assert.equal(models.data.claude.models.length,2);assert.equal(models.data.codex.models.length,2);
 const messages=()=>fs.readFileSync(logFile,'utf8').trim().split('\n').map(JSON.parse).filter(l=>l.event==='input'&&l.type==='user');
 const chatFile=()=>path.join(home,'decks',fs.readdirSync(path.join(home,'decks'))[0],'chat.json');
 const chat=()=>JSON.parse(fs.readFileSync(chatFile()));
 await api('message',{text:'Keep the headings blue.'});await until(()=>fs.existsSync(chatFile())&&chat().chat.some(e=>e.kind==='turn'));
 const oldId=chat().sessionId;
 const slideId=fs.readFileSync(path.join(deck,'index.html'),'utf8').match(/<section[^>]*data-eid="([^"]+)"/)[1];
 assert.equal((await api('notes',{eid:slideId,text:'Notes kept through provider switches.'})).status,200);
 let r=await api('settings',{provider:'codex',model:'gpt-fail',handover:'fresh'});assert.equal(r.status,400);assert.match(r.data.error,/startup failure/);assert.equal(chat().sessionId,oldId);
 r=await api('settings',{provider:'codex',model:'gpt-test'});assert.equal(r.status,400);
 r=await api('settings',{provider:'codex',model:'gpt-test',handover:'summary'});assert.equal(r.status,200);await until(()=>chat().provider==='codex');assert.equal(chat().sessionArchive[0].id,oldId);
 assert.equal(JSON.parse(fs.readFileSync(path.join(home,'config.json'))).effortPreferences['claude:sonnet'],'medium');
 const firstCodex=chat().sessionId;
 await api('message',{text:'Continue.'});await until(()=>fs.readFileSync(logFile,'utf8').includes('Continue.'));
 const logs=messages();assert.match(logs.at(-1).text,/Keep the headings blue/);
 await until(()=>chat().chat.filter(e=>e.kind==='turn').length===2);
 r=await api('settings',{effort:'low'});assert.equal(r.status,200);assert.equal(chat().sessionId,firstCodex);
 r=await api('settings',{provider:'claude',model:'haiku',handover:'fresh'});assert.equal(r.status,200);assert.equal(r.data.settings.effort,null);assert.equal(chat().handover,'');
 await api('message',{text:'New topic.'});await until(()=>fs.readFileSync(logFile,'utf8').includes('New topic.'));
 const last=messages().at(-1);assert(!last.text.includes('Keep the headings blue'));
 await until(()=>chat().chat.filter(e=>e.kind==='turn').length===3);
 assert.equal((await api('undo',{})).status,200);
 assert(!fs.readFileSync(path.join(deck,'index.html'),'utf8').includes('Notes kept through provider switches.'));
 assert.equal((await api('redo',{})).status,200);
 assert(fs.readFileSync(path.join(deck,'index.html'),'utf8').includes('Notes kept through provider switches.'));
 const saved=JSON.parse(fs.readFileSync(path.join(home,'config.json')));
 assert.equal(saved.effortPreferences['codex:gpt-test'],'low');
 r=await api('settings',{provider:'codex',model:'gpt-test',handover:'fresh'});
 assert.equal(r.status,200);assert.equal(r.data.settings.effort,'low');
 const beforeFailure=fs.readFileSync(path.join(home,'config.json'),'utf8');
 r=await api('settings',{model:'not-in-catalog'});assert.equal(r.status,400);
 assert.equal(fs.readFileSync(path.join(home,'config.json'),'utf8'),beforeFailure);
 assert.equal(fs.readFileSync(path.join(deck,'theme.css'),'utf8'),'h1 { color: blue; }');assert.equal(errors,'');
});
